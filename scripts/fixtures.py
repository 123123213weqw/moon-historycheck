"""Run the same golden API cases on all four MoonBit backends."""
import json,os,shutil,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];DEST=ROOT/'fixtures_wbtest.mbt'
def literal(value):return json.dumps(json.dumps(value,ensure_ascii=False,separators=(',',':')),ensure_ascii=False)
def main():
    cases=json.loads((ROOT/'tests/cases.json').read_text(encoding='utf-8'))
    code='// Generated by scripts/fixtures.py from tests/cases.json.\n\n///|\nfn fixture_at(value : Value, parts : Array[String]) -> Value {\n  let mut current=value\n  for part in parts { current=match current { Object(fields)=>fields[part]; _=>abort("fixture path not object") } }\n  current\n}\n'
    for case in cases:
        code+='\n///|\ntest '+json.dumps('fixture '+case['name'],ensure_ascii=False)+' {\n  let result=from_json(execute(@json.parse('+literal(case['request'])+')))\n'
        for key,expected in case['expected'].items():code+='  assert_eq(fixture_at(result,'+json.dumps(key.split('/'))+'),from_json(@json.parse('+literal(expected)+')))\n'
        code+='}\n'
    old=DEST.read_text(encoding='utf-8') if DEST.exists() else None
    DEST.write_text(code,encoding='utf-8')
    home=os.environ.get('MOON_HOME');binary=Path(home)/'bin'/('moon.exe' if os.name=='nt' else 'moon') if home else shutil.which('moon')
    subprocess.run([str(binary),'fmt'],cwd=ROOT,check=True,capture_output=True)
    current=DEST.read_text(encoding='utf-8')
    if '--check' in sys.argv and current!=old:
        if old is not None:DEST.write_text(old,encoding='utf-8')
        raise SystemExit('Generated fixtures are stale')
    print('Golden API fixtures:',len(cases),'up to date')
if __name__=='__main__':main()
